"""Version-bound research obligations. No execution, paid calls or state acceptance."""
from __future__ import annotations

import hashlib
from typing import Literal
from urllib.parse import urlsplit

from pydantic import Field, model_validator

from .models import CaseContext, Investigation, MatcherResult, Model, VersionRef, evidence_hash, investigation_key

ResearchState = Literal["research_required", "actively_researching", "reassessment_required", "ready_for_human_review",
                        "monitor", "human_research_required", "supported_outside_scope", "decline"]


class ResearchPoint(Model):
    id: str = Field(min_length=1)
    criterion_ids: list[str] = Field(default_factory=list)
    question: str = Field(min_length=1)
    decision_consequence: str = Field(min_length=1)
    what_to_obtain: str = Field(min_length=1)
    evidence_ids: list[str] = Field(default_factory=list)
    investigation: Investigation | None = None


class ResearchAttempt(Model):
    task_id: str = Field(min_length=1)
    question_id: str
    investigation_key: str | None = None
    status: Literal["queued", "running", "succeeded", "failed", "inaccessible", "no_answer", "exhausted"]
    summary: str = Field(min_length=1)
    accepted_evidence_ids: list[str] = Field(default_factory=list)
    source_urls: list[str] = Field(default_factory=list)
    attempted_at: str | None = None

    @model_validator(mode="after")
    def safe_attempt(self):
        from datetime import datetime
        if self.attempted_at is not None:
            time = datetime.fromisoformat(self.attempted_at.replace("Z", "+00:00"))
            if time.tzinfo is None:
                raise ValueError("Attempt time must retain timezone")
        for url in self.source_urls:
            parsed = urlsplit(url)
            if parsed.scheme not in {"http", "https"} or not parsed.hostname or parsed.username or parsed.password:
                raise ValueError("Attempt source must be an attributable HTTP(S) URL without credentials")
        return self


class ResearchTaskIntent(Model):
    kind: Literal["investigate_claim"] = "investigate_claim"
    assessment_ref: str
    input_ref: VersionRef
    question_id: str
    idempotency_key: str
    investigation: Investigation
    acceptance: Literal["backend_reserves_executes_persists_then_reassesses"] = "backend_reserves_executes_persists_then_reassesses"


class HumanResearchPoint(Model):
    question_id: str
    question: str
    what_to_obtain: str
    decision_consequence: str
    evidence_ids: list[str]
    why_agent_stopped: str
    attempted_task_ids: list[str]


class ReviewCheck(Model):
    status: Literal["supported", "mixed", "contradicted", "unknown"]
    explanation: str = Field(min_length=1)
    evidence_ids: list[str] = Field(default_factory=list)


class ProductReviewCheck(ReviewCheck):
    basis: Literal["inspected_documentation", "inspected_prototype", "inspected_experiment", "hands_on_workflow", "source_claim_only", "unknown"]


class FounderReviewCheck(ReviewCheck):
    person_ids: list[str] = Field(default_factory=list)


class MaterialContradiction(Model):
    id: str
    explanation: str = Field(min_length=1)
    evidence_ids: list[str] = Field(min_length=1)
    resolved: bool


class HumanContradictionAcceptance(Model):
    """Backend-supplied durable reviewer action; never generated by the agent."""
    review_record_id: str = Field(min_length=1)
    assessment_ref: str
    input_ref: VersionRef
    contradiction_ids: list[str]
    current: bool


class Section9Readiness(Model):
    assessment_ref: str
    input_ref: VersionRef
    primary_track: Literal["H", "R", "D", "T"]
    identity_and_scope: ReviewCheck
    problem_or_program: ReviewCheck
    founder_contribution: FounderReviewCheck
    differentiated_approach: ReviewCheck
    product_or_experimental_gate: ProductReviewCheck
    material_contradictions: list[MaterialContradiction] = Field(default_factory=list)
    human_contradiction_acceptance: HumanContradictionAcceptance | None = None
    remaining_risks: list[str] = Field(min_length=1)


class BoundaryConclusion(Model):
    kind: Literal["supported_outside_scope", "decline"]
    basis: Literal["confirmed_sector_mismatch", "no_repeatable_core_after_investigation", "approved_boundary_failure", "human_pass"]
    rationale: str = Field(min_length=1)
    evidence_ids: list[str] = Field(min_length=1)
    criterion_id: str | None = None
    human_pass_record_ref: str | None = None


class ResearchFollowThrough(Model):
    schema_version: Literal["0.1"] = "0.1"
    input_ref: VersionRef
    assessment_input_ref: VersionRef
    assessment_ref: str
    state: ResearchState
    explanation: str
    task_intents: list[ResearchTaskIntent] = Field(default_factory=list)
    active_task_ids: list[str] = Field(default_factory=list)
    human_research_points: list[HumanResearchPoint] = Field(default_factory=list)
    accepted_delta_evidence_ids: list[str] = Field(default_factory=list)
    reassessment_required: bool = False
    future_trigger: str | None = None
    review_kind: Literal["investment_human", "specialist_human"] | None = None
    readiness: Section9Readiness | None = None
    readiness_gaps: list[str] = Field(default_factory=list)
    boundary: BoundaryConclusion | None = None
    authority: Literal["research_workflow_not_qualification_or_execution"] = "research_workflow_not_qualification_or_execution"


def _sourced(context, ids):
    evidence = {e.id: e for e in context.evidence}
    return bool(ids) and all(eid in evidence and evidence[eid].admissible and evidence[eid].freshness != "stale"
        and (evidence[eid].source_key or evidence[eid].source_url)
        and (evidence[eid].data_mode != "synthetic" or context.test_fixture) for eid in ids)


def _readiness_gaps(context, report, assessment_ref):
    if report.input_ref != context.ref or report.assessment_ref != assessment_ref:
        raise ValueError("Readiness must bind the current context and immutable assessment")
    gaps = []
    for label in ["identity_and_scope", "problem_or_program", "founder_contribution", "differentiated_approach", "product_or_experimental_gate"]:
        check = getattr(report, label)
        if check.status != "supported" or not _sourced(context, check.evidence_ids):
            gaps.append(label)
    founder = report.founder_contribution
    people = {p.id for p in context.people}
    for person_id in founder.person_ids:
        if person_id not in people:
            raise ValueError("Readiness cites an unknown person")
    if not founder.person_ids or not all(
        any(e.subject_kind == "person" and e.subject_id == pid and e.id in founder.evidence_ids for e in context.evidence)
        and any(r.person_id == pid and r.status == "supported" and _sourced(context, r.evidence_ids) for r in context.relationships)
        for pid in founder.person_ids):
        gaps.append("attributed_founder_work")
    if report.product_or_experimental_gate.basis in {"source_claim_only", "unknown"}:
        gaps.append("inspected_track_appropriate_artifact")
    if report.primary_track in {"D", "T"} and report.product_or_experimental_gate.basis not in {"inspected_prototype", "inspected_experiment"}:
        gaps.append("track_appropriate_experimental_or_prototype_evidence")
    contradictions = report.material_contradictions
    if len({c.id for c in contradictions}) != len(contradictions):
        raise ValueError("Duplicate material contradiction IDs")
    if any(not _sourced(context, c.evidence_ids) for c in contradictions):
        gaps.append("contradiction_provenance")
    unresolved = {c.id for c in contradictions if not c.resolved}
    acceptance = report.human_contradiction_acceptance
    accepted = set()
    if acceptance is not None:
        if acceptance.input_ref != context.ref or acceptance.assessment_ref != assessment_ref or not acceptance.current:
            raise ValueError("Human contradiction acceptance is stale or bound to another assessment")
        accepted = set(acceptance.contradiction_ids)
        if not accepted <= {c.id for c in contradictions}:
            raise ValueError("Human acceptance cites unknown contradictions")
    if unresolved - accepted:
        gaps.append("unresolved_material_contradictions")
    return list(dict.fromkeys(gaps))


def _default_point(result):
    assessment = result.assessment
    brief = assessment.case_brief
    inv = assessment.investigation
    question = inv.question if inv else ("What evidence resolves this uncertainty: " + brief.decisive_doubt.text if brief else assessment.next_action)
    consequence = inv.decision_consequence if inv else "Resolve the saved decisive uncertainty before further pursuit or human review."
    obtain = brief.next_action if brief else assessment.next_action
    ids = brief.decisive_doubt.evidence_ids if brief else []
    return ResearchPoint(id="question:" + hashlib.sha256(question.encode()).hexdigest()[:20],
        criterion_ids=[inv.criterion_id] if inv else [], question=question, decision_consequence=consequence,
        what_to_obtain=obtain, evidence_ids=ids, investigation=inv)


def plan_follow_through(context: CaseContext, matcher_result: MatcherResult, *, assessment_ref: str,
                        questions: list[ResearchPoint] | None = None, attempts: list[ResearchAttempt] | None = None,
                        readiness: Section9Readiness | None = None, boundary: BoundaryConclusion | None = None,
                        current_ref: VersionRef | None = None) -> ResearchFollowThrough:
    """Propose bounded follow-through or an explicit human handoff; never claim execution.

    Backend passes truthful attempts and accepted rebuilt evidence, then executes
    task_intents, persists outcomes and invokes reassessment outside transactions.
    Reference-comparison policy is sufficient for research, not qualification.
    """
    if context.ref.evidence_hash != evidence_hash(context) or current_ref is not None and current_ref != context.ref:
        raise ValueError("Follow-through snapshot is stale")
    if matcher_result.ref.case_id != context.ref.case_id or not assessment_ref.strip():
        raise ValueError("Follow-through needs this case's immutable assessment reference")
    if matcher_result.assessment is None or matcher_result.outcome not in {"assessment", "needs_approval"}:
        raise ValueError("A saved rich comparison is required")
    result = dict(input_ref=context.ref, assessment_input_ref=matcher_result.ref, assessment_ref=assessment_ref)
    changed = context.ref.evidence_hash != matcher_result.ref.evidence_hash or context.ref.policy_version != matcher_result.ref.policy_version or context.ref.thesis_version != matcher_result.ref.thesis_version
    attempts = attempts or []
    known = {e.id for e in context.evidence}
    if len({a.task_id for a in attempts}) != len(attempts) or any(not set(a.accepted_evidence_ids) <= known for a in attempts):
        raise ValueError("Attempts need unique durable task IDs and accepted evidence in the rebuilt context")
    if changed:
        return ResearchFollowThrough(**result, state="reassessment_required", explanation="Accepted evidence or mandate meaning changed; reassess the rebuilt joint context before another pursuit decision.",
            accepted_delta_evidence_ids=list(dict.fromkeys(context.changed_evidence_ids + [eid for a in attempts for eid in a.accepted_evidence_ids])), reassessment_required=True)
    if boundary is not None:
        if not (context.policy.approved or context.policy.reference_direction_reviewed):
            raise ValueError("Scope/pass conclusion requires reviewed mandate meaning")
        if not _sourced(context, boundary.evidence_ids):
            raise ValueError("Outside-scope/pass requires supported sourced facts, not search failure")
        if boundary.basis == "no_repeatable_core_after_investigation" and not any(a.status in {"succeeded", "no_answer"} for a in attempts):
            raise ValueError("No-repeatable-core conclusion requires recorded investigation, not a keyword")
        if boundary.basis == "human_pass" and not boundary.human_pass_record_ref:
            raise ValueError("Human pass needs a durable reviewer record")
        if boundary.basis == "approved_boundary_failure":
            criterion = next((c for c in context.policy.criteria if c.id == boundary.criterion_id), None)
            finding = next((f for f in matcher_result.assessment.findings if f.criterion_id == boundary.criterion_id), None)
            if not context.policy.approved or criterion is None or not criterion.reject_on_failure or finding is None or finding.result != "fails" or not finding.evidence_sufficient or finding.conflicted:
                raise ValueError("Decline requires a supported approved rejection boundary")
        elif boundary.kind == "decline" and boundary.basis != "human_pass":
            raise ValueError("Reference scope conclusion cannot silently become investment decline")
        return ResearchFollowThrough(**result, state=boundary.kind, explanation=boundary.rationale, boundary=boundary)
    points = questions if questions is not None else [_default_point(matcher_result)]
    if len({p.id for p in points}) != len(points):
        raise ValueError("Duplicate research question IDs")
    criteria = {c.id for c in context.policy.criteria}
    for point in points:
        if not set(point.criterion_ids) <= criteria or not set(point.evidence_ids) <= known:
            raise ValueError("Research point cites nonexistent criteria/evidence")
    active = [a.task_id for a in attempts if a.status in {"queued", "running"}]
    if active:
        return ResearchFollowThrough(**result, state="actively_researching", explanation="Backend-reported research work is queued/running; a recommendation is not completion.", active_task_ids=active, readiness=readiness)
    if readiness is not None:
        gaps = _readiness_gaps(context, readiness, assessment_ref)
        if not gaps:
            return ResearchFollowThrough(**result, state="ready_for_human_review", explanation="Section9 evidence supports a review packet; remaining risks and human qualification are separate.",
                readiness=readiness, review_kind="specialist_human" if readiness.primary_track in {"D", "T"} else "investment_human")
    else:
        gaps = []
    brief = matcher_result.assessment.case_brief
    if brief and brief.research_posture == "monitor" and brief.future_trigger:
        return ResearchFollowThrough(**result, state="monitor", explanation=brief.main_reason.text, future_trigger=brief.future_trigger, readiness=readiness)
    remaining = context.resources.remaining_calls
    intents, handoff = [], []
    for point in points:
        history = [a for a in attempts if a.question_id == point.id]
        inv = point.investigation
        key = investigation_key(context.ref.case_id, inv) if inv else None
        blocker = None
        if history or key in context.attempted_investigation_keys:
            blocker = "Recorded attempt did not resolve this question in the current assessment; do not repeat unchanged research."
        elif inv is None:
            blocker = "No validated executable investigation is mapped to this specific question."
        elif not (context.policy.approved or context.policy.reference_direction_reviewed):
            blocker = "Research direction is not approved/reviewed."
        elif context.resources.deadline_expired:
            blocker = "Execution deadline is exhausted; company merit is unchanged."
        elif inv.max_calls > remaining:
            blocker = "Remaining execution allowance cannot cover this bounded action; company merit is unchanged."
        elif not any(c.purpose == "investigation" and c.action == inv.action and inv.subject_kind in c.subject_kinds for c in context.capabilities):
            blocker = "No permitted capability can execute this action."
        else:
            scope = {"company": {context.company_id}, "person": {p.id for p in context.people}, "relationship": {r.id for r in context.relationships}, "market": {e.subject_id for e in context.evidence if e.subject_kind == "market"}}
            if inv.criterion_id not in criteria or inv.subject_id not in scope[inv.subject_kind] or inv.question != point.question or inv.decision_consequence != point.decision_consequence:
                raise ValueError("Investigation must match its point, criterion and canonical subject")
            if any(x.idempotency_key == key for x in intents):
                blocker = "An identical investigation intent is already proposed."
        if blocker:
            handoff.append(HumanResearchPoint(question_id=point.id, question=point.question, what_to_obtain=point.what_to_obtain,
                decision_consequence=point.decision_consequence, evidence_ids=point.evidence_ids, why_agent_stopped=blocker,
                attempted_task_ids=[a.task_id for a in history]))
        else:
            intents.append(ResearchTaskIntent(assessment_ref=assessment_ref, input_ref=context.ref, question_id=point.id, idempotency_key=key, investigation=inv))
            remaining -= inv.max_calls
    if not intents and not handoff:
        point = _default_point(matcher_result)
        handoff.append(HumanResearchPoint(question_id=point.id, question=point.question, what_to_obtain=point.what_to_obtain, decision_consequence=point.decision_consequence,
            evidence_ids=point.evidence_ids, why_agent_stopped="No actionable research point or sourced section9 readiness was supplied.", attempted_task_ids=[]))
    return ResearchFollowThrough(**result, state="research_required" if intents else "human_research_required",
        explanation="Backend must accept and execute these bounded tasks, then rebuild context and reassess." if intents else "Give these unresolved research points to the human before further pursuit; a recommendation has not completed research.",
        task_intents=intents, human_research_points=handoff, readiness=readiness, readiness_gaps=gaps)
